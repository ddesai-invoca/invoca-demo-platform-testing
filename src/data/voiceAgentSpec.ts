/* =============================================================================
   voiceAgentSpec.ts — a prospect's own Qualify-and-Route configuration
   -----------------------------------------------------------------------------
   The voice workflow's CONTENT for one prospect: what the intent looks like, how the agent
   opens the call, the qualifying question and its answers, and the routing steps including
   the service-area check.

   ⚠️ **WHY AN OVERRIDE TABLE RATHER THAN GENERATED DATA.** Everything else on this screen is
   derived per prospect, and for most of them derivation is right — it costs no generation time
   and every demo on disk gets it. But an SE configuring a real agent types THESE words: the
   exact greeting, the exact ZIP codes, the exact sentence read to a caller outside the service
   area. Deriving those would be inventing them. Same pattern and same matcher as `SHAPE` and
   `SMS_SHAPE` in AgentWorkflow: keyed by prospect NAME through `isProspect`, never a guessed
   id, because these demos live in the shared library and their ids are whatever the SE typed.

   ⚠️ **EVERY PROSPECT NOW GETS THIS TEMPLATE (8/27/2026), DERIVED WHERE IT IS NOT CONFIGURED.**
   It used to return null for anyone but Comfort Keepers, and the consequence was measured
   across all 12 profiles on disk: 8 of them never asked for a ZIP and **11 never asked for a
   name**, while every one of them drew "Consumer Zip" and "Consumer Name" pills on the
   diagram. The tree advertised collecting two things the agent never collected, and nothing
   failed. `deriveVoiceSpec` closes that by building the same shape from the prospect's own
   profile, so a demo generated by any SE behaves like the configured one.

   ⚠️ **DERIVED, NOT GENERATED — no engine phase and no schema slice**, so generation time is
   unchanged and every demo already in the shared library gets it without regenerating.

   ⚠️ **AN EXPLICIT SPEC STILL WINS OUTRIGHT.** Where an SE typed the words, those are the
   words: `SPECS` is searched first and derivation only fills the gap.
   ============================================================================= */

/** The configured specs write the greeting as their last conversation rule; so does the
    derived one. `specWithConfig` finds it by this prefix to keep the copy in step. */
export const GREETING_RULE_PREFIX = "This is how you should also greet and start a phone call: ";

export interface VoiceAgentSpec {
  /** Matched with `isProspect`, so any id the SE typed still resolves. */
  prospect: string;
  /** "What does this intent look like?" — the description AND the opening line. */
  intent: string;
  /** What the agent says first. Also the last of the conversation rules, as the real one has it. */
  greeting: string;
  /** The Qualify leaf's question. */
  qualifyQuestion: string;
  /**
   * The branches under the two user-group nodes, one per USE CASE.
   *
   * ⚠️ **THIS REPLACED A FIXED PAIR OF SALES SEGMENTS (8/27/2026)**, at the user's request:
   * "those 2 can have as many branches as the user want, those branches represent use cases."
   * The old `segments: [string, string]` was a TUPLE, so the type itself made a third sales
   * branch impossible and the support node could not branch at all. Both limits were ours,
   * not the product's.
   */
  useCases: VoiceUseCases;
  /** What the agent says when it cannot tell which answer it heard. */
  qualifyFallback: string;
  /** The intent's conversation rules, in order. */
  rules: string[];
  /**
   * ⚠️ **AN ALLOW-LIST, WHICH INVERTS THE DEMO GATE.** The generic voice prompt treats a single
   * ZIP ("12345") as the only OUT-of-area one, so every other ZIP proceeds — right for a
   * national business. This prospect serves three ZIPs and turns everything else away, so the
   * polarity is the other way round and `buildVoiceSystem` has to be told which it is.
   */
  serviceZips?: string[];
  /** Read verbatim to a caller outside the service area. */
  outOfAreaScript?: string;
  /** The Inform & Route steps, verbatim, in the SE's own numbering. */
  informSteps: string[];
  /**
   * What the agent does when a caller needs the support team.
   *
   * ⚠️ IT WAS A LITERAL INSIDE `workflowDrawers.ts` UNTIL 9/21/2026, which meant the drawer
   * showed an instruction the PROMPT never carried — the drawer-describes-something-the-agent-
   * does-not shape this file records three times. Optional, defaulting to the same wording, so
   * an agent nobody has edited reads exactly as before.
   */
  escalateHandling?: string;
  /**
   * The SUPPORT intent's own description and conversation rules.
   *
   * ⚠️ BOTH WERE HARDCODED UNTIL 9/21/2026 — the description was a literal in
   * `workflowDrawers.ts` and the rules were a bare `[]` — so the Need Support drawer showed
   * five read-only boxes on the one page where the words ARE the prompt. Optional, and both
   * fall back to exactly what was hardcoded, so an untouched agent is byte-identical.
   */
  supportIntent?: string;
  supportRules?: string[];
  /**
   * Which voice the agent speaks with — a `VOICE_OPTIONS` id like "thalia".
   *
   * ⚠️ **NOT PART OF THE PROMPT, and that is why it lives here rather than in `ChatBrain`.**
   * `voiceSystemPrompt` turns a brain into words the agent says; a TTS voice is how it says
   * them. It rides to the worker beside `greeting` as a per-call operational field.
   * Absent means `DEFAULT_VOICE_ID`, which is the voice every demo already had.
   */
  voice?: string;
}

